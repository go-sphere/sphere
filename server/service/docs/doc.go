// Package docs runs a development documentation server as a core/task.Task.
// It aggregates the Swagger specs of several API services behind one address
// and proxies "Try it out" calls to each service.
//
// For every [Target] the server registers, under the lowercased swag instance
// name of its spec:
//
//   - /{name}/doc/swagger/ — Swagger UI, whose doc.json points at the proxy;
//   - /{name}/api/... — a reverse proxy to Target.Address with the prefix
//     stripped;
//
// and a single index page at "/" listing all targets.
//
// # Usage
//
//	import (
//		"github.com/go-sphere/sphere/core/boot"
//		"github.com/go-sphere/sphere/server/service/docs"
//		apidocs "example.com/app/api/docs" // generated by swag
//	)
//
//	web := docs.NewWebServer(docs.Config{
//		Address: ":9999",
//		Targets: []docs.Target{
//			{Address: "http://localhost:8080", Spec: apidocs.SwaggerInfo},
//		},
//	})
//	return boot.NewApplication(apiServer, web), nil
//
// [NewWebServer] owns a private net/http server listening on Config.Address;
// [NewWebServerWithEngine] mounts the same handlers on a caller-provided
// httpx engine, and [Web.Register] mounts them on any root router.
//
// Every response carries permissive CORS headers (Access-Control-Allow-Origin
// "*", without credentials) and OPTIONS requests are answered with 204. The
// server is meant for development; do not expose it publicly.
package docs
