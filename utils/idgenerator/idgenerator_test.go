// TestStressConcurrentIdGeneration satisfies Objective 3:
// 50+ concurrent goroutines generating IDs, verifying strictly unique, increasing integers.
func TestStressConcurrentIdGeneration(t *testing.T) {
	const (
		numGoroutines   = 64
		idsPerGoroutine = 5000
		totalExpected   = numGoroutines * idsPerGoroutine
	)

	var wg sync.WaitGroup
	idMatrix := make([][]int64, numGoroutines)

	for g := range numGoroutines {
		wg.Add(1)
		go func(gID int) {
			defer wg.Done()
			ids := make([]int64, idsPerGoroutine)
			for i := range idsPerGoroutine {
				id := NextId()
				if id <= 0 {
					t.Errorf("goroutine %d generated non-positive ID: %d", gID, id)
				}
				if i > 0 && id <= ids[i-1] {
					t.Errorf("goroutine %d generated non-increasing ID: prev=%d, curr=%d", gID, ids[i-1], id)
				}
				ids[i] = id
			}
			idMatrix[gID] = ids
		}(g)
	}

	wg.Wait()

	// Verify all generated IDs across all goroutines are strictly unique
	seen := make(map[int64]int, totalExpected)
	for gID, ids := range idMatrix {
		for idx, id := range ids {
			if prevG, exists := seen[id]; exists {
				t.Fatalf("Duplicate ID %d detected! Generated by goroutine %d (index %d) and goroutine %d",
					id, gID, idx, prevG)
			}
			seen[id] = gID
		}
	}

	if len(seen) != totalExpected {
		t.Fatalf("Total unique IDs = %d, want %d", len(seen), totalExpected)
	}

	t.Logf("Successfully generated and verified %d strictly unique IDs across %d concurrent goroutines",
		totalExpected, numGoroutines)
}

// TestStressIndependentWorkerGenerators verifies independent instances of NewIdGenerator
// running across different worker IDs concurrently.
func TestStressIndependentWorkerGenerators(t *testing.T) {
	workerIDs := []uint16{0, 1, 10, 31, 63}
	const count = 1000

	var wg sync.WaitGroup
	allIDs := sync.Map{}

	for _, wID := range workerIDs {
		wg.Add(1)
		go func(w uint16) {
			defer wg.Done()
			gen := NewIdGenerator(w)
			var prev int64
			for i := range count {
				id := gen()
				if id <= 0 {
					t.Errorf("worker %d generated non-positive ID: %d", w, id)
				}
				if i > 0 && id <= prev {
					t.Errorf("worker %d non-increasing ID: prev=%d, curr=%d", w, prev, id)
				}
				prev = id

				if _, loaded := allIDs.LoadOrStore(id, w); loaded {
					t.Errorf("collision detected on ID %d from worker %d", id, w)
				}
			}
		}(wID)
	}

	wg.Wait()
}

